"""ATOM-DIET-TRAJECTORY-1 instrument (pre-reg RESULTS L66546, sealed by
AMENDMENT -SEAL L66822): paired stock/atoms births at the matched
15,420-step horizon with snapshot emission. Sibling of the results-cited
scratch/birth19m_atoms_ladder.py (not edited): the recipe, dose
mechanics, no-op precondition and training loop are verbatim. Changes:
(i) snapshots saved at the frozen schedule (step 0, 463, then every
1,028 to 15,420); (ii) the arm's three actual token-id batch-stream
digests are asserted against the pinned values before the first
optimizer step; (iii) unique output paths under checkpoints/atomtraj1/;
(iv) non-finite loss aborts; (v) NO gate runs in this file (post-hoc
gates: scratch/birth19m_atoms_trajgate.py). Every receipt field is
derived from the artifacts this process opened or wrote.

Env: ARM=stock|atoms SEED=<int> [ORDER_INDEX=<0..5>]
     SMOKE=1        path-isolated (checkpoints/atomtraj1_smoke/,
                    logs/atomtraj1/smoke.jsonl), seed must be >= 11,
                    steps capped at SMOKE_STEPS (default 1,100),
                    optional TAG suffix on the output directory
     DRYRUN=1       stream assertions only, exit before any output
     EMIT=0         skip snapshot files (CPU emission-neutrality probe
                    only; smoke mode required)
     DEVICE=cpu     device override (probe only; smoke mode required)

Usage: ARM=stock SEED=5 ORDER_INDEX=0 .venv/bin/python scratch/birth19m_atoms_traj.py
"""
