"""VERIFIED-ENDOGENOUS-DATA-CROSSFOSTER-1, donor-library stage (PRE-REG
VERIFIED-ENDOGENOUS-DATA-CROSSFOSTER-1-DONOR). Zero training. Builds the
two matched donor libraries D_A = G(W_A) and D_B = G(W_B) from the two
function-matched seed-2 specimens of WRITER-TRAJECTORY-CENSUS-0:
  A = forward OneCycle final, checkpoints/gallery19m_phase_s2.pt
  B = backward OneCycle final, checkpoints/gallery19m_backsched_s2.pt
(both from the seed-2 W_0; state digests asserted against
logs/writertraj0/census.json; the census receipts are the shared-W_0 and
function-band evidence and are re-read, never recomputed, here).

Root population (fresh, frozen before any donor output is read): roots
r = (level, seed) with seed = ROOT_BAND + 1000 * level + I0 + i, i <
N_PER_LEVEL[level], levels 3..7 in the atoms-shard mix (level 4 twice the others),
enumerated in a fixed order whose every prefix carries the population's
level mix (sorted by fractional progress per level; root_order), each
generated by llmopt.lab.gen._gen_isolated (make_integrate, fork-timeboxed)
into cur = "Integral(<sstr expr>, x)". A root is EXCLUDED before any
generation if norm(cur) is in the gate band (tenet_d2_revdiet.
gate_band_exprs), in the base diet's cur or nxt strings (the D2-excised
stock rows, the training data of both donors), or duplicates an earlier
root's norm(cur); generation failures (None) are excluded with a count.

Generation law, IDENTICAL for A and B: for each root, N_WAVES waves of
the standard gate sampler llmopt.lab.gate.sample_wave_lp (B = 8 samples
per wave, temperature 0.7, max_new 120, KV-cached; the same function the
gate uses), prompt "Current: <cur>\\nHints: none\\nStep: ", sampling seeds
SAMPLE_BAND + 1000 * root_index + 8 * wave + b (b < 8; the same seeds for
both donors); candidates deduplicated by whitespace-stripped text;
IDENTITY-REJECTION: a candidate whose norm equals norm(cur) is rejected
before the oracle; the exact oracle llmopt.lab.verify.verify_wave(cur,
candidates) decides PASS (ok) and SOLVED; only PASS candidates are
eligible. The donor's rows for a root are its distinct PASS candidates in
sampling order; canonical row identity = (norm(cur), norm(nxt)).

Matched-root / matched-dose retention (K frozen): a root is RETAINED
iff BOTH donors supplied >= K distinct PASS rows; each donor then
contributes exactly its first K PASS rows for that root. Roots are
processed in the fixed order until N_RETAIN roots are retained or the
population is exhausted; every processed root is accounted (retained /
excluded-band / excluded-diet / excluded-dup / gen-failed / inadequate-A /
inadequate-B / inadequate-both). D_A and D_B therefore have identical
root support and size N_RETAIN * K. If fewer than N_RETAIN roots are
retained from the whole population: DONOR-INACCESSIBLE.

Library row schema (mechanically the atoms-shard schema, so the
ATOM-DIET exposure law applies unchanged): {"cur", "nxt", "level",
"rule": "donor", "source": "donor-A" | "donor-B", "root_index",
"root_seed", "sample_seed", "wave", "solved"}; the recipient driver
encodes cur / nxt / level only.

Descriptive readouts (never alter K, dose, generator or the factorial):
verified yield per donor (PASS rows / samples), adequacy per donor,
retained-root count and level mix, exact and canonical overlap between
D_A and D_B (rows with equal (norm(cur), norm(nxt))), novelty v the base
diet (rows whose canonical nxt is any diet cur / nxt string), solved
fraction, nxt token-length distribution, and the cross-model teacher-
forced CE of each library under each donor (A on D_A, A on D_B, B on
D_A, B on D_B; eligible label positions, the trainer's encoding).

Outputs: data/crossfoster1/D_A.jsonl, data/crossfoster1/D_B.jsonl
(refuse-if-exists), logs/crossfoster1/donor.json (accounting, readouts,
digests of both libraries), logs/crossfoster1/donor.jsonl. SMOKE=1:
population 20 roots (4 per level), N_RETAIN 4, N_WAVES 1, outputs under
data/crossfoster1_smoke<SMOKE_TAG>/ and logs/crossfoster1/smoke<SMOKE_TAG>.jsonl.
Usage: .venv/bin/python scratch/crossfoster_donor.py
"""
