"""MATH-CYBER-1 AX-FIXTURE-0 — the frozen ActionProgram
interchange fixture for Axiom Tranche A
(AX-MATHCYBER-ACTIONPROGRAM-FIXTURE-0).

Emits, under logs/mathworld1/axfixture/ (refuse-if-exists):
- parents.jsonl: every parent of the frozen 101-decision corpus —
  fixture_id, episode_id/step_id, parent_id (srepr sha16),
  state_srepr (authoritative interchange), state_sstr
  (model-facing print), state_visible_v1 (the original v1 visible
  string, evidence binding), n_legal (complete legal-set
  cardinality), visible_match flag (sstr == v1 string; a
  MEASUREMENT, never normalized).
- actions.jsonl: all 725 legal actions under the canonical
  ACTION-FINAL schema — rule, site_kind (W|D|I|L), site_ordinal
  (first-preorder unique-site law; -1 for whole-expression),
  param_kind (none|u_choice|term_index), param_index (-1 for
  none), program_text (ActionGCTok serialization, diagnostic
  only — structured fields are the semantic identity), child_sstr,
  child_srepr, child_hash, rule_target (historical provenance).
- unprod_stress.jsonl: all 2,894 PDC-matched unique i_unprod
  edges (term_index stress stratum, SEPARATE replay denominator) —
  cur_sha, cur (visible string domain, the PDC law), site_ordinal,
  term_index, program_text, child_sstr.
- axfixture_manifest.json: counts, per-file sha256, producer file
  shas (start_provenance), bar booleans.

Semantic parameter fields are GENERATED by rule semantics only
(iparts_children u_choice map; trace_unprod term map; deterministic
single-accepted-child assert) — never by child-key/hash-sorted
selection. Replay self-bars re-decode every row from the
structured fields alone before the fixture is considered emitted.

Zero model, zero training, zero fresh seeds, zero search, zero
Axiom mutation.

    .venv/bin/python scratch/mathworld1_axfixture.py        (Mac)
"""
